#!/usr/bin/env node
// PreToolUse guard: refuse hand-edits to the living capability specs.
//
// openspec/specs/ is generated. `openspec archive` folds an applied change's delta into
// it; nothing else writes there. An agent that edits the living spec directly produces a
// spec that no change proposed, no human approved at Gate B, and no archive will ever
// reconcile — and the drift is silent, which is what makes it expensive.
//
// The legitimate exception is correcting drift, where the code is right and the spec is
// wrong. That is a deliberate act, so enabling it is deliberate too:
//
//   OPENSPEC_ALLOW_SPEC_EDIT=1
//
// Written for node rather than bash+jq on purpose. This workspace already requires node
// (the openspec CLI does), while jq is absent on plenty of developer machines — and a
// fail-closed guard whose only dependency is missing denies every write in the repo,
// which reads as a broken workspace rather than as protection.
//
// Fails CLOSED. If the root is unknown or the payload will not parse, the write is denied
// rather than allowed: an unreadable input is not evidence that the target is safe.

import { resolve } from "node:path";

function respond(reason) {
  if (reason) {
    process.stdout.write(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: reason,
        },
      }),
    );
  }
  process.exit(0);
}

// Backslashes to forward slashes, then lowercase, so Windows and POSIX spellings compare.
const norm = (p) => resolve(p).replaceAll("\\", "/").toLowerCase().replace(/\/$/, "");

async function main() {
  // An explicit, deliberate override for drift correction.
  if (process.env.OPENSPEC_ALLOW_SPEC_EDIT === "1") respond();

  const root = process.env.CLAUDE_PROJECT_DIR;
  if (!root) {
    respond(
      "BLOCKED: CLAUDE_PROJECT_DIR is unset, so this guard cannot tell whether the write target is a living capability spec under openspec/specs/.",
    );
  }

  let raw = "";
  for await (const chunk of process.stdin) raw += chunk;

  let target;
  try {
    const payload = JSON.parse(raw);
    target = payload?.tool_input?.file_path ?? payload?.tool_input?.notebook_path ?? "";
  } catch {
    respond(
      "BLOCKED: this guard could not parse the tool payload, so it cannot tell whether the write target is a living capability spec under openspec/specs/.",
    );
  }

  // A tool invocation with no file target has nothing to guard.
  if (!target) respond();

  // Match the living specs only — never openspec/changes/<name>/specs/, which is where a
  // delta is supposed to be written.
  if (norm(target).startsWith(`${norm(root)}/openspec/specs/`)) {
    respond(
      "BLOCKED: openspec/specs/ holds the LIVING capability specs, which are generated by 'openspec archive' — they are never hand-edited as part of a change. Write the delta to openspec/changes/<change-name>/specs/<capability>/spec.md instead, and let the archive fold it in. If you are deliberately correcting drift between the spec and shipped code, set OPENSPEC_ALLOW_SPEC_EDIT=1 and say so at the next gate.",
    );
  }

  respond();
}

main().catch((error) => {
  respond(
    `BLOCKED: this guard failed before it could check the write target (${error?.message ?? error}), so it cannot tell whether the target is a living capability spec under openspec/specs/.`,
  );
});
